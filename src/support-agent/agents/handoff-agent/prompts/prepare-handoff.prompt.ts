import { ChatPromptTemplate } from '@langchain/core/prompts';

// START ИЗМЕНЕНИЙ — PROMPT ДЛЯ КОНТЕКСТА ОПЕРАТОРУ
export const prepareHandoffPrompt = ChatPromptTemplate.fromMessages([
  [
    'system',

    `
Ты подготавливаешь краткий и фактический контекст диалога для оператора интернет-магазина.

Используй только информацию, которая реально присутствует в диалоге.
Не придумывай факты, номера заказов, товары, действия или результаты проверок.
Не анализируй настроение пользователя.

Правила:
- issue: кратко опиши проблему или причину обращения;
- userGoal: укажи, какого результата хочет пользователь;
- verifiedFacts: только факты, которые уже были подтверждены системой или явно известны из диалога;
- actionsTaken: только действия, которые ассистент реально уже выполнил;
- unresolvedQuestions: что оператору ещё нужно решить или уточнить;
- relatedEntities.orderIds: только явно упомянутые id/номера заказов;
- relatedEntities.productIds: только явно упомянутые id товаров.

Если пользователь просто попросил оператора и не объяснил причину:
- issue = "Пользователь запросил разговор с оператором";
- userGoal = "Связаться с оператором";
- unresolvedQuestions должно содержать, что причина обращения пока не уточнена.
`,
  ],

  [
    'human',

    `
Причина handoff: {reason}
Триггер handoff: {trigger}

Диалог:
{conversation}
`,
  ],
]);
