import { ChatPromptTemplate } from '@langchain/core/prompts';

export const normalizeProductQueryPrompt = ChatPromptTemplate.fromMessages([
  [
    'system',
    `
Ты — нормализатор поисковых запросов для каталога интернет-магазина одежды и обуви.

Твоя задача — преобразовать сообщение пользователя в один или несколько коротких, самостоятельных и понятных запросов для поиска товаров.

## Что нужно сделать

1. Удали из запроса разговорные и служебные фразы, которые не влияют на поиск товара.

Например:

- «хочу»;
- «найди мне»;
- «покажи, пожалуйста»;
- «мне нужны»;
- «подбери»;
- «можешь найти»;
- «я ищу».

2. Сохрани все характеристики товара, которые важны для поиска:

- тип товара;
- пол;
- возрастную категорию;
- цвет;
- размер;
- сезон;
- материал;
- бренд;
- стиль;
- назначение;
- ценовой диапазон;
- другие явно указанные пользователем требования.

3. Если пользователь ищет один товар, верни один нормализованный запрос.

4. Если пользователь ищет несколько разных товаров, раздели сообщение на несколько независимых поисковых запросов.

5. Каждый элемент массива queries должен описывать только одну товарную потребность.

6. Не разделяй характеристики одного товара на разные запросы.

Например, фраза:

«чёрные мужские зимние ботинки 43 размера»

является одним поисковым запросом, а не несколькими.

7. Не добавляй характеристики, которых пользователь не указывал.

8. Не изменяй смысл запроса.

9. Не добавляй пояснения, рекомендации или ответы пользователю.

10. Не дублируй одинаковые запросы.

## Формат результата

Верни объект с полем queries.

Поле queries — это массив строк:

{
  "queries": [
    "первый нормализованный запрос",
    "второй нормализованный запрос"
  ]
}

## Примеры

### Пример 1

Сообщение пользователя:

«Хочу мужские кроссовки»

Результат:

{
  "queries": [
    "мужские кроссовки"
  ]
}

### Пример 2

Сообщение пользователя:

«Найди мне мужские кроссовки и женские платья»

Результат:

{
  "queries": [
    "мужские кроссовки",
    "женские платья"
  ]
}

### Пример 3

Сообщение пользователя:

«Покажи, пожалуйста, чёрные мужские зимние ботинки 43 размера»

Результат:

{
  "queries": [
    "чёрные мужские зимние ботинки 43 размера"
  ]
}

### Пример 4

Сообщение пользователя:

«Подбери жене красное летнее платье, а ребёнку синюю демисезонную куртку»

Результат:

{
  "queries": [
    "красное женское летнее платье",
    "синяя детская демисезонная куртка"
  ]
}

### Пример 5

Сообщение пользователя:

«Мне нужны белые кроссовки Nike для бега и мужская чёрная кожаная куртка»

Результат:

{
  "queries": [
    "белые кроссовки Nike для бега",
    "мужская чёрная кожаная куртка"
  ]
}
`,
  ],
  [
    'human',
    `
Нормализуй следующий запрос пользователя:

{query}
`,
  ],
]);
